"""Candidate-facing templates grounded only in submitted structured choices."""
TASKS = {
 'organizational': 'Вы выбрали организационное направление: помощь на событиях и взаимодействие с посетителями.',
 'project': 'Вы выбрали проектное направление: квесты, мастер-классы и образовательные форматы.',
 'collections': 'Вы выбрали фондовое направление. Места ограничены; обсудите с координатором интересующие коллекции и альтернативы.',
 'inclusive': 'Вы выбрали инклюзивное направление: сопровождение и доступность музейных программ. Конкретные задачи и подготовку обсудите с координатором.',
 'media': 'Вы выбрали медиа: фото, видео, тексты или дизайн. Конкретные задачи и возможность обучения обсудите на собеседовании.',
 'undecided': 'Вы пока не определились с направлением. Координатор поможет сопоставить ваши интересы с доступными задачами.'}


def feedback(data):
    parts=[TASKS[data.desired_direction]]
    if data.availability_hours_month == 0:
        parts.append('Вы указали 0 часов в месяц. Обсудите, возможен ли подходящий формат участия; регулярные смены пока не согласованы.')
    else:
        parts.append(f'Вы указали {data.availability_hours_month} ч/месяц. Это ваша доступность, а не подтверждённый график; дни и смены нужно согласовать.')
    text=data.expectations.casefold()
    if any(term in text for term in ('зарплат','трудоустр','оплачиваем','оплату','заработ')):
        parts.append('Это волонтёрская программа; она не гарантирует оплачиваемую работу или трудоустройство.')
    parts.append('Направление, место, обучение и приём не гарантированы. Окончательное решение принимает координатор после собеседования.')
    return ' '.join(parts)
